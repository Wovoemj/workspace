/**
 * ============================================
 * 表单验证工具函数
 * ============================================
 * 
 * 【功能说明】
 * - 邮箱格式验证
 * - 手机号格式验证（中国大陆）
 */

/**
 * 验证邮箱格式
 * 
 * @param s - 待验证的字符串
 * @returns 是否为有效的邮箱格式
 * 
 * @验证规则】
 * - 必须包含@符号
 * - @前后的用户名不能有空格
 * - 必须有域名和点号
 */
export function isValidEmail(s: string) {
  // 空值检查
  if (!s || typeof s !== 'string') return false
  // 正则：任意非空字符 + @ + 任意非空字符 + . + 任意非空字符
  return /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(s.trim())
}

/**
 * 验证手机号格式（中国大陆）
 * 
 * @param s - 待验证的字符串
 * @returns 是否为有效的手机号
 * 
 * @验证规则】
 * - 必须以1开头
 * - 第二位必须是3-9
 * - 总共11位数字
 * - 允许存在空格、横杠等分隔符（会自动去除）
 * 
 * @支持格式
 * - 13812345678（标准格式）
 * - 138-1234-5678（带分隔符）
 * - +86 13812345678（国际格式前缀）
 */
export function isValidPhone(s: string) {
  // 空值检查
  if (!s || typeof s !== 'string') return false
  // 正则：1开头，第二位3-9，后面9位数字
  // 允许空格和横杠，会先去除
  return /^1[3-9]\d{9}$/.test(s.trim().replace(/[\s\-]/g, ''))
}
